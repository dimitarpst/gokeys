// Builds the gokeys marks and icons from GoTypeface-Heavy.ttf (the govrse brand face).
//
// Family rule (gowake/docs/BRIEF.md): set the name in the brand face, keep the letter shapes untouched, and replace
// the "o" with a disc whose counter says what the app does. For gokeys the counter is a keyboard: a rounded-rect
// cut-out with keys left standing inside it (even-odd: disc, hole, keys).
//
// Outputs (all regenerated, never hand-edited):
//   gokeys_logo.svg      wordmark, mint "go" + off-white "keys"
//   gokeys_logo_sm.svg   the "go" mark on a transparent 800x800 square
//   icons/*.png          the app icon at every size Windows asks for (mint tile, ink mark)
//   gokeys.ico           app + tray icon (the exe's own icon, via gokeys.rc)
//   offline.ico, paused.ico   tray icon while not connected / paused
//   fonts/gokeys_*.ttf   Roboto Regular/Medium cut down to Latin-1, embedded for the window text
//
// Run:  npm install && npm run logo
import fs from "node:fs";
import path from "node:path";
import opentype from "opentype.js";
import { Resvg } from "@resvg/resvg-js";

const DIR = path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1"));
const font = opentype.loadSync(path.join(DIR, "GoTypeface-Heavy.ttf"));

export const MINT = "#5ED6A0";
const INK = "#0E1A14";
const OFFWHITE = "#ECF1EE";

// Font units, y down after flipping: "k" reaches 702 above the baseline, "g" descends 231 below it.
const TOP = 702, BOTTOM = -231, HEIGHT = TOP - BOTTOM;
// The font's own "o": a disc 552 wide on a 576 advance, centred at (288, 270).
const O_CX = 288, O_CY = 270, O_R = 276;

const f = (v) => (Math.round(v * 10) / 10).toString();
const glyph = (ch, dx) => font.charToGlyph(ch).getPath(dx, TOP, font.unitsPerEm).toPathData(1);
const advance = (ch) => font.charToGlyph(ch).advanceWidth;

const circle = (cx, cy, r) => `M${f(cx - r)} ${f(cy)}A${r} ${r} 0 1 0 ${f(cx + r)} ${f(cy)}A${r} ${r} 0 1 0 ${f(cx - r)} ${f(cy)}Z`;

function roundRect(x, y, w, h, r) {
  return `M${f(x + r)} ${f(y)}H${f(x + w - r)}A${r} ${r} 0 0 1 ${f(x + w)} ${f(y + r)}V${f(y + h - r)}`
    + `A${r} ${r} 0 0 1 ${f(x + w - r)} ${f(y + h)}H${f(x + r)}A${r} ${r} 0 0 1 ${f(x)} ${f(y + h - r)}`
    + `V${f(y + r)}A${r} ${r} 0 0 1 ${f(x + r)} ${f(y)}Z`;
}

/** The disc with a keyboard cut out: a row of four keys over a space bar, all kept bold enough for 16 px. */
function keyboardO(dx) {
  const cx = O_CX + dx, cy = TOP - O_CY;
  const w = 372, h = 252, pad = 40, gap = 30;
  const x0 = cx - w / 2, y0 = cy - h / 2;
  const key = (w - 2 * pad - 3 * gap) / 4; // four keys across
  const rowH = (h - 2 * pad - gap) / 2;
  const parts = [circle(cx, cy, O_R), roundRect(x0, y0, w, h, 52)];
  for (let i = 0; i < 4; i++) parts.push(roundRect(x0 + pad + i * (key + gap), y0 + pad, key, rowH, 18));
  parts.push(roundRect(x0 + pad + key + gap, y0 + pad + rowH + gap, 2 * key + gap, rowH, 18)); // space bar
  return parts.join("");
}

/** The "go" pair and its bounding box. */
function goMark() {
  const d = glyph("g", 0) + keyboardO(advance("g"));
  return { d, box: [12, TOP - 546, advance("g") + O_CX + O_R, TOP - BOTTOM] };
}

function write(name, data) {
  const file = path.join(DIR, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
  console.log("wrote", name);
}

// Wordmark.
let x = 0;
let go = "", keys = "";
for (const ch of "gokeys") {
  if (ch === "o") go += keyboardO(x);
  else if (ch === "g") go += glyph(ch, x);
  else keys += glyph(ch, x);
  x += advance(ch);
}
write("gokeys_logo.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${x} ${HEIGHT}" width="${x}" height="${HEIGHT}">
  <!-- gokeys wordmark. Generated by branding/make-logo.mjs from GoTypeface-Heavy; recolour by swapping fills only. -->
  <path fill="${MINT}" fill-rule="evenodd" d="${go}"/>
  <path fill="${OFFWHITE}" d="${keys}"/>
</svg>
`);

const { d: mark, box: [bx0, by0, bx1, by1] } = goMark();
const bw = bx1 - bx0, bh = by1 - by0;

/** The mark fitted to [width] and centred in a [size] square. */
function placed(size, width, fill) {
  const s = width / bw;
  const tx = (size - bw * s) / 2 - bx0 * s, ty = (size - bh * s) / 2 - by0 * s;
  return `<path fill="${fill}" fill-rule="evenodd" transform="translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${s.toFixed(6)})" d="${mark}"/>`;
}

write("gokeys_logo_sm.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800" width="800" height="800">
  <!-- The "go" mark. Generated by branding/make-logo.mjs. -->
  ${placed(800, 730, "#282828")}
</svg>
`);

/** A rounded tile with the mark; small sizes get a bigger mark so it stays readable in the tray. */
function iconSvg(size, tile, ink) {
  const markWidth = size * (size <= 24 ? 0.86 : size <= 48 ? 0.8 : 0.72);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  <rect width="${size}" height="${size}" rx="${size * 0.22}" fill="${tile}"/>
  ${placed(size, markWidth, ink)}
</svg>`;
}

const png = (svg) => new Resvg(svg, { shapeRendering: 2 }).render().asPng();

/** .ico with PNG entries (Windows Vista and later read these at every size). */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4);
    header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((i) => i.data)]);
}

const SIZES = [16, 20, 24, 32, 40, 48, 64, 256];
for (const [name, tile, ink] of [["gokeys", MINT, INK], ["offline", "#8A9590", INK], ["paused", "#3A423E", "#8A9590"]]) {
  const images = SIZES.map((size) => ({ size, data: png(iconSvg(size, tile, ink)) }));
  if (name === "gokeys") for (const { size, data } of images) write(`icons/icon_${size}.png`, data);
  write(`${name}.ico`, ico(images));
}

// Roboto (the go* apps' text face), cut down to Latin-1 plus a little punctuation: key names on German and English
// layouts all fit, and the exe stays small. Linked via gokeys.rc.
const { default: subsetFont } = await import("subset-font");
let chars = "…·–—‘’“”•→←↑↓";
for (let c = 0x20; c <= 0xff; c++) chars += String.fromCharCode(c);
for (const weight of ["regular", "medium"]) {
  const full = fs.readFileSync(path.join(DIR, "fonts", `roboto_${weight}.ttf`));
  write(`fonts/gokeys_${weight}.ttf`, await subsetFont(full, chars, { targetFormat: "truetype" }));
}
